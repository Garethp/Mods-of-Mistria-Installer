namespace Garethp.ModsOfMistriaInstallerLib.Seam;

// The generated mmapi_install_stamp.gml: the installer release that built the
// archive, as one global. Readers use the accessor form, so a build without
// the stamp sees undefined rather than a compile error.
public static class InstallStampRenderer
{
    public const string Global = "__mmapi_installer_version";

    public static string Render(string version)
    {
        var literal = version.Replace("\\", "\\\\").Replace("\"", "\\\"");
        return string.Join("\n",
        [
            "//",
            "// mmapi_install_stamp.gml -- GENERATED BY MOMI, DO NOT EDIT.",
            "// The installer release that built this archive. Read it through",
            $"// global[$ \"{Global}\"], which is undefined when no stamp is installed.",
            "//",
            "",
            $"global.{Global} = \"{literal}\";",
            "",
        ]);
    }
}
