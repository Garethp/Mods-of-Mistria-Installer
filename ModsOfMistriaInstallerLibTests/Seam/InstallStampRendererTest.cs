using Garethp.ModsOfMistriaInstallerLib.Seam;

namespace ModsOfMistriaInstallerLibTests.Seam;

[TestFixture]
public class InstallStampRendererTest
{
    [Test]
    public void ShouldPublishTheReleaseAsOneGlobal()
    {
        var rendered = InstallStampRenderer.Render("0.17.0");

        Assert.That(rendered, Does.StartWith("//"));
        Assert.That(rendered, Does.Contain("GENERATED BY MOMI"));
        Assert.That(rendered, Does.Contain("global.__mmapi_installer_version = \"0.17.0\";\n"));
        Assert.That(rendered, Does.Not.Contain("function "),
            "the stamp defines no function, so a build without it never fails to compile");
    }

    [Test]
    public void ShouldEscapeTheLiteral()
    {
        var rendered = InstallStampRenderer.Render("1.0\"\\x");

        Assert.That(rendered, Does.Contain("global.__mmapi_installer_version = \"1.0\\\"\\\\x\";"));
    }
}
